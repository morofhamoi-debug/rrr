-- KHAMOI database schema
-- Run the complete script in Supabase Dashboard -> SQL Editor.

create table if not exists public.users (
  id text primary key,
  username text,
  first_name text not null default 'Участник',
  last_name text,
  referred_by text references public.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.referrals (
  id bigint generated by default as identity primary key,
  inviter_id text not null references public.users(id) on delete cascade,
  referred_id text not null unique references public.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  constraint referrals_no_self check (inviter_id <> referred_id)
);

create index if not exists referrals_inviter_idx on public.referrals(inviter_id);
create index if not exists referrals_created_at_idx on public.referrals(created_at desc);

create table if not exists public.giveaways (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  prize integer not null check (prize > 0),
  channel text,
  ends_at timestamptz not null,
  status text not null default 'active' check (status in ('active', 'finished')),
  created_by text references public.users(id) on delete set null,
  telegram_message_id bigint,
  winner_id text references public.users(id) on delete set null,
  winner_name text,
  created_at timestamptz not null default now(),
  finished_at timestamptz
);

create index if not exists giveaways_status_ends_idx on public.giveaways(status, ends_at);

-- Aggregated view used by the public leaderboard.
create or replace view public.referral_totals as
select
  u.id as user_id,
  u.first_name,
  u.username,
  count(r.id)::integer as referrals_count,
  max(r.created_at) as created_at
from public.users u
left join public.referrals r on r.inviter_id = u.id
group by u.id, u.first_name, u.username;

-- The backend uses the Supabase service-role key. Do not expose it in frontend code.
alter table public.users enable row level security;
alter table public.referrals enable row level security;
alter table public.giveaways enable row level security;

-- No public policies are created intentionally. All data access goes through the trusted backend.
